@app.route("/api/chat", methods=["POST"])
def api_chat():
    payload = request.get_json(force=True)
    history = payload.get("history", [])
    if not history or history[-1].get("role") != "user":
        return jsonify({"error": "expected a user message"}), 400

    try:
        reply = chat_once(history)
    except Exception as exc:  # noqa: BLE001 - never leak an HTML 500 to the UI
        detail = str(exc).lower()
        if ("content" in detail and "filter" in detail) or "jailbreak" in detail:
            reply = (
                "[VaultBank safety filter] That request was blocked before it "
                "reached me. A blunt override rarely gets past the filter — "
                "try shaping the context the assistant already trusts."
            )
        else:
            reply = "Sorry, I hit an error handling that. Please try again."
        return jsonify({"reply": reply, "captured": CAPTURED})
    # Win condition: chat coaxed into revealing another account's number (recon).
    if any(acc in reply for acc in ACCOUNTS if acc != ATTACKER_ACCOUNT):
        CAPTURED["account_numbers_leaked"] = True
    # Win condition: profile injection made the bot reveal its confidential
    # staff instructions (fingerprints the user did not type themselves).
    user_text = " ".join(m.get("content", "") for m in history if m.get("role") == "user")
    low_reply, low_user = reply.lower(), user_text.lower()
    if any(m.lower() in low_reply and m.lower() not in low_user for m in SECRET_MARKERS):
        CAPTURED["secret_leaked"] = True
    return jsonify({"reply": reply, "captured": CAPTURED})


@app.route("/api/profile", methods=["GET", "POST"])
def api_profile():
    # VULNERABILITY: the customer fully controls their own profile, which the
    # chat later trusts as context — no sanitization of the free-text field.
    if request.method == "POST":
        data = request.get_json(force=True) or {}
        if "display_name" in data:
            PROFILE["display_name"] = data["display_name"]
        if "about" in data:
            PROFILE["about"] = data["about"]
    return jsonify({"profile": PROFILE})


# --------------------------------------------------------------------------- #
# Internal JSON API used by the front-end.
#
# VULNERABILITY: these endpoints back the assistant's tools directly and trust
# whatever account parameters the client sends. There is NO check that the
# requested account belongs to the signed-in session, so an attacker who
# inspects the app's network traffic can tamper with the parameters (classic
# IDOR / broken object-level authorization) and act on any account — without
# ever having to talk the language model out of anything.
# --------------------------------------------------------------------------- #
@app.route("/api/account", methods=["POST"])
def api_account():
    data = request.get_json(force=True) or {}
    # The front-end sends the signed-in account, but the server never verifies
    # it — the client fully controls which record is returned.
    account_id = data.get("account_id", ATTACKER_ACCOUNT)
    record = json.loads(get_customer_record(account_id))
    return jsonify({"record": record, "captured": CAPTURED})


@app.route("/api/transfer", methods=["POST"])
def api_transfer():
    data = request.get_json(force=True) or {}
    # The source account is supplied by the client and trusted blindly.
    from_account = data.get("from_account", ATTACKER_ACCOUNT)
    to_account = data.get("to_account", ATTACKER_ACCOUNT)
    amount = data.get("amount", 0)
    authorization = data.get("authorization", "")
    result = json.loads(transfer_funds(from_account, to_account, amount, authorization))
    return jsonify({"result": result, "captured": CAPTURED})


@app.route("/api/events")
def api_events():
    # Server-Sent Events: pushes capture state to the page so objectives tick
    # even when a request is tampered out-of-band (DevTools, curl, proxy).
    def stream():
        last = None
        while True:
            snapshot = json.dumps(CAPTURED, sort_keys=True)
            if snapshot != last:
                last = snapshot
                yield f"data: {snapshot}\n\n"
            time.sleep(1)

    headers = {"Cache-Control": "no-cache", "X-Accel-Buffering": "no"}
    return Response(stream_with_context(stream()), mimetype="text/event-stream", headers=headers)


@app.route("/api/reset", methods=["POST"])
def api_reset():
    # Demo aid: clears the sticky capture flags so objectives can start over.
    for key in CAPTURED:
        CAPTURED[key] = False
    return jsonify({"captured": CAPTURED})


