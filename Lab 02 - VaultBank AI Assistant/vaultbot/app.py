"""
VaultBank AI Assistant — "VaultBot"
------------------------------------
Intentionally VULNERABLE customer-support chatbot used for the
"Be The Hacker" LLM security lab (Lab 02).

DO NOT deploy this anywhere real. It is deliberately insecure so learners can
practise prompt injection, system-prompt leakage, sensitive-data disclosure,
insecure tool use (excessive agency), and guardrail bypass.

Configuration + protected data are generated by the (hidden) setup script and
loaded at runtime from:
  - .env                 -> Azure OpenAI endpoint / key / deployment
  - .secrets/vault_data.json -> system prompt, accounts, master code, flags

The values are randomised per setup run and are git-ignored, so reading this
source file does not reveal the answer. You must extract it from the running
model.
"""

