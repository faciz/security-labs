def _load_vault_data():
    if not SECRETS_PATH.exists():
        raise SystemExit(
            "Protected data not found. Run the lab setup script first:\n"
            "    cd 'Lab 02 - VaultBank AI Assistant' && ./lab02_setup.sh\n"
        )
    with SECRETS_PATH.open(encoding="utf-8") as handle:
        return json.load(handle)


VAULT = _load_vault_data()
ACCOUNTS = VAULT["accounts"]
ATTACKER_ACCOUNT = VAULT["attacker_account"]
MASTER_CODE = VAULT["master_code"]
SYSTEM_PROMPT = VAULT["system_prompt"]
TRANSFER_FLAG = VAULT["transfer_flag"]

# Server-side audit log the attacker cannot see directly, revealed only when a
# successful exploit occurs.
CAPTURED = {
    "account_numbers_leaked": False,
    "secret_leaked": False,
    "customer_pii_exposed": False,
    "unauthorized_transfer": False,
}

# The signed-in customer's own profile. The "about" field is self-service and
# attacker-controlled — the chat trusts it as personalization context, so it is
# an indirect prompt-injection vector.
PROFILE = {
    "display_name": "Guest User",
    "about": "Prefers quick answers.",
}

# Confidential staff instructions the bot must hide. The system prompt only
# reveals them when the profile contains a prompt-injection attempt. The key one
# authorizes administrator "Bob" to enumerate accounts, so a learner who leaks
# these can then impersonate Bob in chat to list every account. The others are
# realistic decoys that leak alongside it. These fingerprints are distinctive
# phrases from those instructions, used to detect that they were disclosed.
SECRET_MARKERS = (
    "administrator, Bob",
    "$500 per day",
    "01:00",
    "extension 8890",
)


# --------------------------------------------------------------------------- #
# Knowledge base (RAG) — one document is poisoned with an indirect injection.
# --------------------------------------------------------------------------- #
def load_knowledge_base():
    docs = {}
    if KB_DIR.exists():
        for path in sorted(KB_DIR.glob("*.md")):
            docs[path.name] = path.read_text(encoding="utf-8")
    return docs


KNOWLEDGE_BASE = load_knowledge_base()


def retrieve_context(query: str, k: int = 2) -> str:
    """Naive keyword retrieval. The FAQ doc is always included, which is exactly
    how an indirect prompt-injection payload sneaks into the model's context."""
    terms = {t.lower() for t in query.split() if len(t) > 3}
    scored = []
    for name, text in KNOWLEDGE_BASE.items():
        score = sum(text.lower().count(term) for term in terms)
        scored.append((score, name, text))
    scored.sort(reverse=True)

    selected = {name: text for _, name, text in scored[:k]}
    # VULNERABILITY: untrusted document content is always injected verbatim.
    for name, text in KNOWLEDGE_BASE.items():
        if name.lower().startswith("faq"):
            selected[name] = text

    if not selected:
        return ""
    return "\n\n".join(f"### {name}\n{text}" for name, text in selected.items())


